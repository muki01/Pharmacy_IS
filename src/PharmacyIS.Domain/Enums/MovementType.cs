namespace PharmacyIS.Domain.Enums;

/// <summary>
/// Вид на складовото движение. Всяка промяна на наличността се записва
/// в журнала на движенията, което гарантира проследимост и възможност
/// за контролно пресмятане на наличността.
/// </summary>
public enum MovementType
{
    /// <summary>Приход – заприхождаване на количество по доставка.</summary>
    In = 1,

    /// <summary>Разход – изписване на количество при продажба.</summary>
    Out = 2,

    /// <summary>Брак – изписване на количество с изтекъл срок на годност или повреда.</summary>
    WriteOff = 3,

    /// <summary>Сторно – връщане на количество при анулиране на продажба.</summary>
    Reversal = 4
}
